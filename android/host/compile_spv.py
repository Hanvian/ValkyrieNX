#!/usr/bin/env python3
"""Compile a GLSL compute/graphics shader into a C uint32_t word array header."""
import argparse
import os
import platform
import shutil
import struct
import subprocess
import sys
import tempfile


def _find_tool(names, ndk=None):
    for name in names:
        p = shutil.which(name)
        if p:
            return p
    ndk_roots = [ndk] if ndk else []
    for env in ("ANDROID_NDK_HOME", "ANDROID_NDK_ROOT", "ANDROID_NDK"):
        val = os.environ.get(env)
        if val:
            ndk_roots.append(val)
    sysname = platform.system().lower()
    host_tag = {
        "linux": "linux-x86_64",
        "darwin": "darwin-x86_64",
        "windows": "windows-x86_64",
    }.get(sysname, "linux-x86_64")
    for root in ndk_roots:
        if not root:
            continue
        for tag in (host_tag, "darwin-arm64", "linux-x86_64"):
            base = os.path.join(root, "shader-tools", tag)
            for name in names:
                cand = os.path.join(base, name + (".exe" if sysname == "windows" else ""))
                if os.path.isfile(cand):
                    return cand
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("out_h")
    ap.add_argument("symbol")
    ap.add_argument("--ndk", default="")
    args = ap.parse_args()

    glslang = _find_tool(["glslangValidator"], args.ndk)
    glslc = _find_tool(["glslc"], args.ndk)
    spirv_opt = _find_tool(["spirv-opt"], args.ndk)
    spirv_val = _find_tool(["spirv-val"], args.ndk)
    if not glslang and not glslc:
        sys.exit("compile_spv.py: neither glslangValidator nor glslc found (install glslang-tools or pass --ndk)")

    os.makedirs(os.path.dirname(os.path.abspath(args.out_h)), exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, os.path.basename(args.src) + ".spv")
        if glslc:
            subprocess.run([glslc, "--target-env=vulkan1.1", "-O", "-o", spv, args.src], check=True)
        else:
            subprocess.run([glslang, "-V", "--target-env", "vulkan1.1", "-g0", "-o", spv, args.src], check=True, stdout=subprocess.DEVNULL)
            if spirv_opt:
                spv_opt = spv + ".opt"
                if subprocess.run([spirv_opt, "--target-env=vulkan1.1", "-O", spv, "-o", spv_opt], check=False).returncode == 0:
                    os.replace(spv_opt, spv)
        if spirv_val:
            subprocess.run([spirv_val, "--target-env", "vulkan1.1", spv], check=True)
        data = open(spv, "rb").read()

    if len(data) % 4 != 0:
        sys.exit(f"compile_spv.py: SPIR-V length {len(data)} is not 4-byte aligned")
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines = [
        f"// Generated by compile_spv.py from {os.path.basename(args.src)}. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        f"static const uint32_t {args.symbol}[] = {{",
    ]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i : i + 8]) + ",")
    lines.append("};")
    content = "\n".join(lines) + "\n"
    if os.path.isfile(args.out_h) and open(args.out_h, "r").read() == content:
        return
    with open(args.out_h, "w") as f:
        f.write(content)


if __name__ == "__main__":
    main()
